// Mount-destination resolution. Pure path arithmetic with no syscalls, so it
// lives outside the linux-only files and can be tested on any host -- which
// matters, because this is the code that decides whether a spec can write
// outside the container.

package container

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// resolveInRoot turns a container-absolute mount destination into a host path
// inside the rootfs, refusing anything that tries to leave it.
//
// A ".." element is rejected outright rather than cleaned away. Cleaning is
// what makes this look safe without being honest: filepath.Clean("/../etc")
// is "/etc", so joining it onto the root lands inside the container and the
// spec's attempt to escape leaves no trace at all. A destination that says
// "/data/../.." was either generated by something broken or written by
// someone probing, and both are worth an error.
//
// Symlinks are the second half of the problem: a destination of "/link",
// where the image contains /link -> /etc, would otherwise be followed out of
// the rootfs by mount(2). The deepest existing ancestor is resolved and
// re-checked for containment, which catches a symlink that is already in the
// image.
//
// What this does not close is the race: between the check and the mount, a
// process inside the container could replace a component with a symlink.
// Closing that needs openat2 with RESOLVE_IN_ROOT, which is what runc does
// and what this would need to do to be used for anything real. It is stated
// in the README rather than left for someone to discover.
func resolveInRoot(root, destination string) (string, error) {
	if !filepath.IsAbs(destination) {
		return "", fmt.Errorf("mount destination %q must be absolute", destination)
	}
	for _, element := range strings.Split(destination, "/") {
		if element == ".." {
			return "", fmt.Errorf(
				"mount destination %q contains a %q element; write the path you mean", destination, "..")
		}
	}

	absRoot, err := filepath.Abs(root)
	if err != nil {
		return "", fmt.Errorf("resolve rootfs %s: %w", root, err)
	}
	absRoot = filepath.Clean(absRoot)

	target := filepath.Join(absRoot, filepath.Clean(destination))
	if err := checkContained(absRoot, target); err != nil {
		return "", fmt.Errorf("mount destination %q: %w", destination, err)
	}

	// Resolve as much of the path as exists. A symlink deeper than the
	// existing prefix cannot matter, because nothing is there to follow.
	existing := target
	for {
		if _, err := os.Lstat(existing); err == nil {
			break
		}
		parent := filepath.Dir(existing)
		if parent == existing {
			break
		}
		existing = parent
	}
	resolved, err := filepath.EvalSymlinks(existing)
	if err != nil {
		// Nothing resolvable to check; the join above already bounds it.
		return target, nil
	}
	resolvedRoot, err := filepath.EvalSymlinks(absRoot)
	if err != nil {
		resolvedRoot = absRoot
	}
	if err := checkContained(resolvedRoot, resolved); err != nil {
		return "", fmt.Errorf("mount destination %q resolves outside the root filesystem via a symlink: %w",
			destination, err)
	}
	return target, nil
}

func checkContained(root, path string) error {
	if path == root || strings.HasPrefix(path, root+string(os.PathSeparator)) {
		return nil
	}
	return fmt.Errorf("escapes the root filesystem (%s is outside %s)", path, root)
}
